export function pathIndexFor(color: Color, progress: number): number {
  return (PLAYER_START[color] + progress) % PATH_LENGTH;
}

export function cellForHorse(
  color: Color,
  zone: "nest" | "path" | "home",
  progress: number,
  horseId: number,
): { x: number; y: number } {
  if (zone === "nest") return NEST_CELLS[color][horseId];
  if (zone === "home") return HOME_CELLS[color][progress - 1];
  return PATH_CELLS[pathIndexFor(color, progress)];
}
